"""Canary tasks (BUILD-SPEC.md 12.4): a small share of the review queue is a synthetic, clearly fabricated referral with a planted error. No side effect, never touches a real patient.
Approving one alerts the admin SILENTLY; the reviewer is never told.

* THE RATE is a REQUIRED setting with no default (`CAREFLOW_CANARY_RATE`, a fraction; the spec says 1-2%): unset means NO canaries are injected. It must be greater than 0 and at most 0.05 (a typo of
  `2` for `0.02` would otherwise flood the queue); anything else is an error at start-up, never a silent default.
* THE DOCUMENT is fabricated text with a visible synthetic marker and one planted, objectively impossible fact (a date of birth that cannot exist). It contains no clinical content: it names no
  condition, drug, dose or threshold. The planted error is a data-validity error that a careful reviewer rejects.
* origin = `canary` on every record it creates, so it is excluded from live volume, cost and KPI figures (13.6) and shown in its own panel.
* THE ALERT is raised by the same transaction that records the approval (`on_decision`), aimed at admin only, with the decision id as its one opaque reference. Nothing the reviewer receives mentions it.
"""

import os
import random
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Final, Protocol

MAX_RATE: Final = 0.05
MARKER: Final = "SYNTHETIC CANARY - FABRICATED FOR REVIEWER CALIBRATION - NOT A REAL PERSON"


class CanaryError(Exception):
    """Fixed words only."""


def rate_from(environ: Mapping[str, str] | None = None) -> float | None:
    raw = (environ if environ is not None else os.environ).get("CAREFLOW_CANARY_RATE")
    if raw is None or not raw.strip():
        return None
    try:
        value = float(raw)
    except ValueError:
        raise CanaryError("CAREFLOW_CANARY_RATE is not a number") from None
    if not 0 < value <= MAX_RATE:
        raise CanaryError("CAREFLOW_CANARY_RATE must be greater than 0 and at most 0.05")
    return value


def should_inject(rate: float | None, draw: Callable[[], float] = random.random) -> bool:
    """True for about `rate` of calls. No configured rate means never. `draw` is injectable so a test is deterministic."""
    return rate is not None and draw() < rate


@dataclass(frozen=True)
class CanaryReferral:
    text: str
    planted_error: str  # a closed word naming what was planted, kept for the evaluation, never shown to the reviewer


def make_canary_referral(serial: int) -> CanaryReferral:
    """A fabricated referral letter. The planted error is a date of birth in the future of any possible clock (year 2999). Deterministic from `serial`."""
    return CanaryReferral(
        text=(
            f"{MARKER}\nReferral letter {serial:06d}\nPatient: Canary Test {serial:06d}\nDate of birth: 31 February 2999\n"
            "Reason for referral: fabricated placeholder for a reviewer calibration check.\nThis letter was generated by the system and describes no person."
        ),
        planted_error="impossible_date_of_birth",
    )


class AlertWriter(Protocol):
    async def raise_alert(self, *, clinic_id: str, origin: str, alert_class: str, audience_role: str, count: int, ref: str, idempotency_key: str) -> None: ...


async def on_decision(*, origin: str, decision: str, decision_id: str, clinic_id: str, alerts: AlertWriter) -> bool:
    """Called with every recorded review decision. Returns True when a silent admin alert was raised (a canary that was approved). Any other decision, or a non-canary, does nothing."""
    if origin != "canary" or decision != "approve":
        return False
    await alerts.raise_alert(
        clinic_id=clinic_id, origin="canary", alert_class="canary_approved", audience_role="admin", count=1, ref=decision_id, idempotency_key=f"canary-approved:{decision_id}"
    )
    return True
