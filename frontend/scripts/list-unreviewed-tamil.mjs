// Writes TAMIL-UNREVIEWED.md: every Tamil string that has not been reviewed by a native speaker, with its English.
// A key is "reviewed" only if it is listed in src/shared/i18n/ta-reviewed.json (empty until a reviewer signs off).
// `--check` regenerates in memory and exits 1 if the committed file differs, so a new Tamil string cannot ship
// without appearing on the list.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = (f) => JSON.parse(readFileSync(resolve(root, 'src/shared/i18n', f), 'utf8'));

function merge(base, extra) {
  const out = { ...base };
  for (const [k, v] of Object.entries(extra)) out[k] = v && typeof v === 'object' && out[k] && typeof out[k] === 'object' ? merge(out[k], v) : v;
  return out;
}
function flatten(tree, prefix = '') {
  return Object.entries(tree).flatMap(([k, v]) => (typeof v === 'string' ? [[prefix + k, v]] : flatten(v, `${prefix}${k}.`)));
}

const all = (lang) => merge(merge(read(`${lang}.json`), read(`console.${lang}.json`)), read(`f4.${lang}.json`));
const en = Object.fromEntries(flatten(all('en')));
const ta = Object.fromEntries(flatten(all('ta')));
const reviewed = new Set(read('ta-reviewed.json').reviewed);

const escape = (s) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
const rows = Object.keys(ta)
  .filter((k) => !reviewed.has(k))
  .sort()
  .map((k) => `| \`${k}\` | ${escape(en[k] ?? '')} | ${escape(ta[k] ?? '')} |`);

const text = [
  '# Tamil strings awaiting native-speaker review',
  '',
  'Generated by `npm run i18n:list` from `src/shared/i18n/*.json`; do not edit by hand. A key leaves this list only when it is added to',
  '`src/shared/i18n/ta-reviewed.json` by a reviewer. CI fails if this file is out of date.',
  '',
  'Not translated on purpose, pending a clinician or a native reviewer: the clinical task kinds (`tasks.kind.red_flag`,',
  '`tasks.kind.screening_unassessable`, `tasks.kind.triage_proposal`), the referral decision words (`referrals.decision.*`), the',
  'identity-revoke reason words (`patients.revoke.reasons.*`) and every `placeholder.*` string stay in English.',
  '',
  `${rows.length} of ${Object.keys(ta).length} strings are unreviewed.`,
  '',
  '| Key | English | Tamil |',
  '|---|---|---|',
  ...rows,
  '',
].join('\n');

const target = resolve(root, 'TAMIL-UNREVIEWED.md');
if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(target, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (committed.replaceAll('\r\n', '\n') !== text) {
    console.error('TAMIL-UNREVIEWED.md is stale. Run: npm run i18n:list');
    process.exit(1);
  }
  console.log(`TAMIL-UNREVIEWED.md is current (${rows.length} unreviewed strings)`);
} else {
  writeFileSync(target, text);
  console.log(`wrote TAMIL-UNREVIEWED.md (${rows.length} unreviewed strings)`);
}
